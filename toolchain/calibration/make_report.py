#!/usr/bin/env python3
"""Render toolchain/calibration/report.md from results/<variant>.json (written by calibrate.py).

Hand-written analysis of non-matching functions lives in analysis.md and is appended verbatim.
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, 'results')
ORDER = ['dsp', 'dsp-nopch', 'sp5', 'ox', 'ob1', 'gy', 'gf']


def load():
    out = {}
    for p in glob.glob(os.path.join(RESULTS, '*.json')):
        d = json.load(open(p))
        out[d['variant']] = d
    return dict(sorted(out.items(), key=lambda kv: ORDER.index(kv[0]) if kv[0] in ORDER else 99))


def unit_stats(u):
    return u['n_functions'], u['exact'], u['code_bytes'], u['exact_bytes']


def strict_totals(d):
    t = dict(code_identical=0, code_sections=0, data_identical=0, data_sections=0,
             symtab_identical_modulo_labels=0, file_identical_except_timestamp=0)
    for u in d['units'].values():
        for k in t:
            t[k] += (u.get('strict') or {}).get('counts', {}).get(k, 0)
    return t


def pct(a, b):
    return f'{100.0 * a / b:.1f}' if b else '-'


def fmt_id(v):
    return '-' if v is None else f'0x{v:08X} (tool {v >> 16:#x}, build {v & 0xffff})'


def main():
    runs = load()
    lines = ['# Compile-oracle calibration: OP API SDK vs ScriptInterfaceR.lib', '',
             'Generated by `toolchain/calibration/calibrate.py` (rendered by `make_report.py`); do not edit',
             'by hand. Hand analysis is in `analysis.md`, appended below.', '',
             'Target: the 23 `.\\Release\\*.obj` members of `Scripts/Libraries/ScriptInterfaceR.lib`',
             '(13 from `ScriptInterface/`, 10 from `shared/`; the `shared/` ones are byte-identical copies of',
             'the `SharedR.lib` members). Base: our compile of the same `.cpp` from a scratch copy of the SDK.',
             '"Byte-exact" = objdiff reports 100% for the function (instruction bytes and relocation targets).',
             'Function counts are the target object\'s defined functions, so unpaired functions count as misses.',
             '"Strict" = independent check by `strictcmp.py`: every COFF section paired by name and COMDAT',
             'symbol, compared byte for byte with relocations as (offset, type, target name); compiler-internal',
             'labels (`$L`, `$T`, `$SG`, `$E` + number) are first shifted by the dominant per-prefix numbering',
             'offset (reported per file). "Symbol table identical" compares every symbol (name, value, section,',
             'class) in order after that shift.',
             '']
    lines += ['## Summary by variant', '',
              '| Variant | Compiler | Files compiled | Functions byte-exact | % functions | % code bytes | objdiff fuzzy % | Strict: code sections identical | Strict: data sections identical | Symbol tables identical (labels shifted) | Objects identical but for timestamp |',
              '|---|---|---|---|---|---|---|---|---|---|---|']
    for v, d in runs.items():
        n = ex = sz = exb = 0
        comp = sum(1 for u in d['units'].values() if u['compiled'])
        for u in d['units'].values():
            a, b, c, e = unit_stats(u)
            n += a; ex += b; sz += c; exb += e
        fz = d['objdiff'].get('fuzzy_match_percent')
        st = strict_totals(d)
        lines.append(f"| `{v}`: {d['desc']} | msvc{d['compiler']} | {comp}/{len(d['units'])} | {ex}/{n} | "
                     f"{pct(ex, n)} | {pct(exb, sz)} | {'-' if fz is None else f'{fz:.2f}'} | "
                     f"{st['code_identical']}/{st['code_sections']} | {st['data_identical']}/{st['data_sections']} | "
                     f"{st['symtab_identical_modulo_labels']}/{len(d['units'])} | "
                     f"{st['file_identical_except_timestamp']}/{len(d['units'])} |")
    base = runs.get('dsp')
    if base:
        lines += ['', '## Compiler identity (`@comp.id` symbol)', '']
        theirs = {u['target_comp_id'] for u in base['units'].values() if u['has_target']}
        lines.append(f"- retail `ScriptInterfaceR.lib` members: {', '.join(fmt_id(t) for t in sorted(theirs, key=str))}")
        for v, d in runs.items():
            ours = {u['comp_id'] for u in d['units'].values() if u['compiled']}
            lines.append(f"- `{v}` (msvc{d['compiler']}): {', '.join(fmt_id(o) for o in sorted(ours, key=str))}")
        lines += ['', '## Per file (baseline `dsp`)', '',
                  '| File | Project | Functions | Byte-exact | % | % code bytes | objdiff fuzzy % | Strict code / data sections identical | Symbol table identical | Identical but for timestamp | `$L`/`$T` label offset | Compile s |',
                  '|---|---|---|---|---|---|---|---|---|---|---|---|']
        for name, u in base['units'].items():
            a, b, c, e = unit_stats(u)
            m = base['objdiff_units'].get(f"{u['project']}/{name}", {})
            fz = m.get('fuzzy_match_percent')
            sc = (u.get('strict') or {}).get('counts', {})
            offs = sorted({o for o in (u.get('strict') or {}).get('label_offset', {}).values() if o})
            lines.append(f"| {name}.cpp | {u['project']} | {a} | {b} | {pct(b, a)} | {pct(e, c)} | "
                         f"{'-' if fz is None else f'{fz:.2f}'} | "
                         f"{sc.get('code_identical', 0)}/{sc.get('code_sections', 0)} code, "
                         f"{sc.get('data_identical', 0)}/{sc.get('data_sections', 0)} data | "
                         f"{'yes' if sc.get('symtab_identical_modulo_labels') else 'no'} | "
                         f"{'yes' if sc.get('file_identical_except_timestamp') else 'no'} | "
                         f"{', '.join(map(str, offs)) if offs else 0} | {u['secs']} |")
        lines += ['', '## Functions that are not byte-exact (baseline `dsp`)', '']
        miss = [(name, f) for name, u in base['units'].items() for f in u['misses']]
        if not miss:
            lines.append('None.')
        else:
            lines += ['| File | Function | Size | objdiff % | Paired |', '|---|---|---|---|---|']
            for name, f in miss:
                m = '-' if f['match'] is None else f"{f['match']:.2f}"
                lines.append(f"| {name} | `{f['demangled'][:140]}` | {f['size']} | {m} | {f['paired']} |")
        fails = [(n, u) for n, u in base['units'].items() if not u['compiled']]
        if fails:
            lines += ['', '## Compile failures (baseline)', '']
            for n, u in fails:
                lines += [f'### {n}', '', '```', (u['log'] or '').strip()[-1500:], '```', '']
    other = [v for v in runs if v != 'dsp']
    if base and other:
        lines += ['', '## Variant differences from baseline', '',
                  'Functions whose byte-exact status differs from `dsp`:', '']
        bmiss = {(n, f['name']) for n, u in base['units'].items() for f in u['misses']}
        for v in other:
            vmiss = {(n, f['name']) for n, u in runs[v]['units'].items() for f in u['misses']}
            gained, lost = len(bmiss - vmiss), len(vmiss - bmiss)
            lines.append(f'- `{v}`: {gained} gained, {lost} lost')
    ana = os.path.join(HERE, 'analysis.md')
    if os.path.exists(ana):
        lines += ['', open(ana).read().rstrip()]
    open(os.path.join(HERE, 'report.md'), 'w').write('\n'.join(lines) + '\n')
    print('wrote', os.path.join(HERE, 'report.md'))


if __name__ == '__main__':
    main()
